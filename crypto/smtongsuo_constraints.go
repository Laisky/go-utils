package crypto

import (
	"bytes"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/asn1"
	"encoding/hex"
	"strconv"
	"strings"

	"github.com/Laisky/errors/v2"
	"github.com/emmansun/gmsm/smx509"
)

// tongsuoConstraints is a detached description of the requested CA authority and raw extensions.
type tongsuoConstraints struct {
	isCA       bool
	maxPathLen int
	extensions []pkix.Extension
}

// tongsuoTemplateConstraints validates a certificate template and returns the exact constraints to encode and verify.
func tongsuoTemplateConstraints(cert *x509.Certificate) (*tongsuoConstraints, error) {
	if cert == nil {
		return nil, errors.New("certificate template is nil")
	}
	return newTongsuoConstraints(cert.IsCA, cert.MaxPathLen, cert.MaxPathLenZero, cert.ExtraExtensions)
}

// tongsuoCSRConstraints validates signing options and returns the exact constraints to encode and verify.
func tongsuoCSRConstraints(opt *signCSROption) (*tongsuoConstraints, error) {
	maximum := -1
	if opt.maxPathLen != nil {
		maximum = *opt.maxPathLen
	}
	return newTongsuoConstraints(opt.isCA, maximum, maximum == 0, opt.extraExtensions)
}

// newTongsuoConstraints validates path length and extension identities, rejecting ambiguous overrides before invoking a tool.
func newTongsuoConstraints(isCA bool, maximum int, explicitZero bool, extensions []pkix.Extension) (*tongsuoConstraints, error) {
	if maximum < -1 || (explicitZero && maximum != 0) {
		return nil, errors.New("invalid CA path length constraint")
	}
	if maximum == 0 && !explicitZero {
		maximum = -1
	}
	if !isCA && maximum >= 0 {
		return nil, errors.New("only CA certificates may specify a path length constraint")
	}
	result := &tongsuoConstraints{isCA: isCA, maxPathLen: maximum}
	seen := make(map[string]struct{}, len(extensions))
	for _, extension := range extensions {
		if _, err := asn1.Marshal(extension.Id); err != nil {
			return nil, errors.Wrap(err, "invalid extra extension OID")
		}
		oid := extension.Id.String()
		if _, exists := seen[oid]; exists {
			return nil, errors.New("duplicate extra extension OID")
		}
		seen[oid] = struct{}{}
		// These extensions are generated by typed options or the selected key.
		// Do not let an arbitrary raw override contradict those security fields.
		switch oid {
		case "2.5.29.14", "2.5.29.15", "2.5.29.17", "2.5.29.19", "2.5.29.32", "2.5.29.35", "2.5.29.37":
			return nil, errors.Errorf("extra extension %s overrides a generated extension; use its typed option", oid)
		}
		if len(extension.Value) == 0 {
			return nil, errors.New("empty extra extension is not representable by Tongsuo")
		}
		result.extensions = append(result.extensions, pkix.Extension{
			Id:       append(asn1.ObjectIdentifier(nil), extension.Id...),
			Critical: extension.Critical,
			Value:    bytes.Clone(extension.Value),
		})
	}
	return result, nil
}

// basicConstraintsLine returns one complete OpenSSL directive preserving the explicit zero-path-length flag.
func (c *tongsuoConstraints) basicConstraintsLine() string {
	value := "FALSE"
	if c.isCA {
		value = "TRUE"
	}
	if c.maxPathLen >= 0 {
		value += ", pathlen:" + strconv.Itoa(c.maxPathLen)
	}
	return "basicConstraints = critical, CA:" + value + "\n"
}

// extraExtensionLines returns raw DER directives using only validated numeric OIDs and hexadecimal bytes, never OpenSSL expressions.
func (c *tongsuoConstraints) extraExtensionLines() string {
	var lines strings.Builder
	for _, extension := range c.extensions {
		value := strings.ToUpper(hex.EncodeToString(extension.Value))
		octets := make([]string, 0, len(extension.Value))
		for i := 0; i < len(value); i += 2 {
			octets = append(octets, value[i:i+2])
		}
		critical := ""
		if extension.Critical {
			critical = "critical,"
		}
		lines.WriteString(extension.Id.String() + " = " + critical + "DER:" + strings.Join(octets, ":") + "\n")
	}
	return lines.String()
}

// verify checks parsed certificate constraints and each requested extension before any issued DER is returned to a caller.
func (c *tongsuoConstraints) verify(cert *smx509.Certificate) error {
	if !cert.BasicConstraintsValid || cert.IsCA != c.isCA || cert.MaxPathLen != c.maxPathLen || cert.MaxPathLenZero != (c.maxPathLen == 0) {
		return errors.New("issued certificate CA or path length constraints differ from the request")
	}
	basicCritical := false
	for _, extension := range cert.Extensions {
		if extension.Id.Equal(asn1.ObjectIdentifier{2, 5, 29, 19}) {
			basicCritical = extension.Critical
		}
	}
	if !basicCritical {
		return errors.New("issued basic constraints must be critical")
	}
	for _, expected := range c.extensions {
		matches := 0
		for _, actual := range cert.Extensions {
			if !actual.Id.Equal(expected.Id) {
				continue
			}
			matches++
			if actual.Critical != expected.Critical || !bytes.Equal(actual.Value, expected.Value) {
				return errors.Errorf("issued extension %s differs from the request", expected.Id.String())
			}
		}
		if matches != 1 {
			return errors.Errorf("issued extension %s is missing or duplicated", expected.Id.String())
		}
	}
	return nil
}
